// Compiles all example projects with WinAVR avr-gcc, runs a short headless
// simulation as a smoke test and writes js/examples-hex.js
// usage: node tools/build-examples.mjs [path-to-avr-gcc-bin]
import { execFileSync } from 'child_process';
import { mkdtempSync, writeFileSync, readFileSync } from 'fs';
import { tmpdir } from 'os';
import { join, dirname } from 'path';
import { fileURLToPath, pathToFileURL } from 'url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const bin = process.argv[2] || 'C:/WinAVR-20100110/bin';
const imp = (p) => import(pathToFileURL(join(root, p)).href);
await imp('js/parts/index.js');
const { EXAMPLES, buildExample } = await imp('js/examples.js');
const { DEVICES } = await imp('js/mcu/devices.js');
const { Simulator } = await imp('js/sim/simulator.js');

const out = {};
for (const ex of EXAMPLES) {
  const dir = mkdtempSync(join(tmpdir(), 'sms-'));
  const doc = await buildExample(ex);
  const mcu = doc.parts.find((p) => p.type === 'mcu');
  const dev = DEVICES[mcu.props.device];
  const fcpu = parseFloat(mcu.props.clock) * 1e6;
  writeFileSync(join(dir, 'main.c'), ex.code);
  try {
    execFileSync(join(bin, 'avr-gcc'), [`-mmcu=${dev.gccMcu}`, `-DF_CPU=${fcpu}UL`, '-Os', '-Wall', '-std=gnu99', '-o', join(dir, 'main.elf'), join(dir, 'main.c')], { stdio: 'pipe' });
    execFileSync(join(bin, 'avr-objcopy'), ['-O', 'ihex', '-R', '.eeprom', join(dir, 'main.elf'), join(dir, 'main.hex')]);
  } catch (e) {
    console.error(`[${ex.id}] compile failed:\n${e.stderr?.toString() || e.message}`);
    process.exitCode = 1;
    continue;
  }
  const hex = readFileSync(join(dir, 'main.hex'), 'utf8');
  out[ex.id] = hex;
  // smoke test
  mcu.fw = { name: 'main.hex', hex };
  const logs = [];
  const sim = new Simulator(doc, { log: (m, k) => logs.push(`${k}: ${m}`) });
  let serial = '';
  for (const inst of sim.instruments) if (inst.kind === 'terminal') inst.listeners.add((it) => { serial += String.fromCharCode(it.b); });
  const t0 = Date.now();
  let dur = 0;
  for (let f = 1; f <= 60; f++) {
    sim.runUntil(f / 60, 1e9); sim.frame(1 / 60); dur = f / 60;
    // type into every virtual terminal once the firmware is up
    if (f === 30) for (const inst of sim.instruments) if (inst.kind === 'terminal') inst.send([...Buffer.from('hi sim'), 13]);
  }
  const ms = Date.now() - t0;
  const extra = [];
  for (const [id, inst] of sim.instances) {
    const p = doc.parts.find((q) => q.id === id);
    if (inst.lcd) {
      let r = '';
      for (let c = 0; c < 16; c++) r += String.fromCharCode(inst.lcd.charAt(0, c) < 32 ? 0x2a : inst.lcd.charAt(0, c));
      r += '|';
      for (let c = 0; c < 16; c++) r += String.fromCharCode(inst.lcd.charAt(1, c) < 32 ? 0x2a : inst.lcd.charAt(1, c));
      extra.push(`${p.ref} LCD="${r}"`);
    }
    if (inst.el?.bright !== undefined && inst.el.bright > 0.05) extra.push(`${p.ref} on`);
    if (inst.angle !== undefined && p.type === 'servo') extra.push(`${p.ref} ${inst.angle.toFixed(0)}deg`);
    if (inst.rpm !== undefined) extra.push(`${p.ref} ${inst.rpm.toFixed(0)}rpm`);
    if (inst.leds) extra.push(`${p.ref} lit=${inst.leds.filter((l) => l.bright > 0.05).length}/${inst.leds.length}`);
    if (inst.st?.latch !== undefined) extra.push(`${p.ref} latch=${inst.st.latch}`);
  }
  console.log(`[${ex.id}] ${hex.length}B hex, sim ${dur.toFixed(2)}s in ${ms}ms, solves=${sim.circuit.solveCount}`,
    serial ? `serial=${JSON.stringify(serial.slice(0, 90))}` : '', extra.join(' '), logs.length ? logs.slice(0, 3).join('; ') : '');
}
writeFileSync(join(root, 'js/examples-hex.js'), `// Generated by tools/build-examples.mjs (WinAVR avr-gcc) — do not edit\nexport const EXAMPLE_HEX = ${JSON.stringify(out, null, 0)};\n`);
